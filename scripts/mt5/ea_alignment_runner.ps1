}

New-Item -ItemType Directory -Force -Path $ExpertsDir, $TesterProfileDir, $LogDir | Out-Null

$Strategies = @(
    @{
        Name = "1H_M30_4H"
        DirPrefix = "1H_M30_4H"
        Expert = "1H_M30_4H_Strategy_EA"
        SetFile = "1H_M30_4H_Strategy_EA.mt5_raw_research_20260725.set"
        FromDate = "2020.01.02"
