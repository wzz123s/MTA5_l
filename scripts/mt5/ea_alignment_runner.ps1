$ErrorActionPreference = "Stop"

$Workspace = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$MetaEditor = Join-Path $InstallRoot "MetaEditor64.exe"
$Terminal = Join-Path $InstallRoot "terminal64.exe"
$ExpertsDir = Join-Path $TerminalDataPath "MQL5\Experts\Advisors"
$TesterProfileDir = Join-Path $TerminalDataPath "MQL5\Profiles\Tester"
$LogDir = Join-Path $Workspace "ea_alignment_logs"
$TerminalRoot = Split-Path -Parent $TerminalDataPath
$MetaQuotesRoot = Split-Path -Parent $TerminalRoot
$TerminalId = Split-Path -Leaf $TerminalDataPath
$TesterDataPath = Join-Path (Join-Path $MetaQuotesRoot "Tester") $TerminalId

if (-not (Test-Path -LiteralPath $MetaEditor)) {
