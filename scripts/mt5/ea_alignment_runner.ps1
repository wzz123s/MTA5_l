    [string]$InstallRoot = "F:\Program Files\MetaTrader 5 EXNESS",
    [string]$TerminalDataPath = "C:\Users\3762\AppData\Roaming\MetaQuotes\Terminal\B695BCB6C1E6864B6D96307B87B29F16",
    [switch]$RunTester
